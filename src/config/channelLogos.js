// Arquivo (em countries/ do acervo) do logo oficial de um canal, pelo nome base; '' se não houver.
export function officialLogoPath(base) {
  for (const [re, file] of OFFICIAL_LOGOS) if (re.test(base)) return file;
  return '';
}

// Nome do arquivo guardado em public/official-logos/.
// "commons:Arquivo.svg" = arquivo do Wikimedia Commons (logos que o acervo não tem).
export const officialLogoFile = (path) =>
  /^commons:/.test(path)
    ? 'commons-' + path.slice(8).normalize('NFD').replace(/[̀-ͯ]/g, '').toLowerCase().replace(/\.\w+$/, '').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '') + '.png'
    : path.split('/').pop();
